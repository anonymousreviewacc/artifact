package com.example.plgenn.ui;

import android.content.ClipData;
import android.content.ClipboardManager;
import android.content.Context;
import android.os.Bundle;
import android.widget.Button;
import android.widget.TextView;
import android.widget.Toast;
import androidx.appcompat.app.AppCompatActivity;
import com.example.plgenn.PayloadItem;
import com.google.android.material.card.MaterialCardView;
import com.example.plgenn.R;

public class PayloadDetailActivity extends AppCompatActivity {

    private TextView tvPayloadDetail, tvCategory, tvTimestamp;
    private Button btnCopy, btnShare;
    private MaterialCardView cardPayload;
    private PayloadItem payloadItem;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        setContentView(R.layout.activity_detail);  // Make sure this matches your layout file name

        // Initialize views
        tvPayloadDetail = findViewById(R.id.tvPayloadDetail);
        tvCategory = findViewById(R.id.tvCategory);
        tvTimestamp = findViewById(R.id.tvTimestamp);
        btnCopy = findViewById(R.id.btnCopy);
        btnShare = findViewById(R.id.btnShare);
        cardPayload = findViewById(R.id.cardPayload);

        // Get payload data from Intent
        payloadItem = (PayloadItem) getIntent().getSerializableExtra("payload");

        if (payloadItem != null) {
            displayPayload(payloadItem);
        } else {
            // Show error and finish
            Toast.makeText(this, "No payload data found", Toast.LENGTH_SHORT).show();
            finish();
        }

        btnCopy.setOnClickListener(v -> copyToClipboard());
        btnShare.setOnClickListener(v -> sharePayload());
    }

    private void displayPayload(PayloadItem item) {
        tvPayloadDetail.setText(item.getPayload());
        tvCategory.setText("Category: " + item.getCategory());
        tvTimestamp.setText("Generated: " + item.getFormattedTime());
    }

    private void copyToClipboard() {
        if (payloadItem != null) {
            ClipboardManager clipboard = (ClipboardManager) getSystemService(Context.CLIPBOARD_SERVICE);
            ClipData clip = ClipData.newPlainText("Payload", payloadItem.getPayload());
            clipboard.setPrimaryClip(clip);
            Toast.makeText(this, "Payload copied to clipboard", Toast.LENGTH_SHORT).show();
        }
    }

    private void sharePayload() {
        if (payloadItem != null) {
            android.content.Intent shareIntent = new android.content.Intent(android.content.Intent.ACTION_SEND);
            shareIntent.setType("text/plain");
            shareIntent.putExtra(android.content.Intent.EXTRA_TEXT,
                    "Payload Category: " + payloadItem.getCategory() +
                            "\n\nPayload:\n" + payloadItem.getPayload() +
                            "\n\nGenerated by PlGenN");
            startActivity(android.content.Intent.createChooser(shareIntent, "Share Payload"));
        }
    }

    public static void start(Context context, PayloadItem payloadItem) {
        android.content.Intent intent = new android.content.Intent(context, PayloadDetailActivity.class);
        intent.putExtra("payload", payloadItem);
        context.startActivity(intent);
    }
}