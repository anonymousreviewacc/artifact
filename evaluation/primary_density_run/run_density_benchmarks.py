def enc(value):
    # Preserve percent-encoding generated by the app; encode query delimiters and fragments.
    return urllib.parse.quote(str(value), safe="%")


def form(value):
    return urllib.parse.urlencode(value, quote_via=urllib.parse.quote_plus, safe="%")


def route_for(site, category, payload):
    q = enc(payload)
    base = BASES[site]
    if category == "SQL Injection":
        if site == "DVWA": return "GET", f"{base}/vulnerabilities/sqli/?id={q}&Submit=Submit", None, None
        if site == "XVWA": return "POST", f"{base}/xvwa/vulnerabilities/sqli/", form({"search": payload}), "application/x-www-form-urlencoded"
        return "GET", f"{base}/sqli_1.php?title={q}&action=search", None, None
    if category == "XSS":
        if site == "DVWA": return "GET", f"{base}/vulnerabilities/xss_r/?name={q}", None, None
        if site == "XVWA": return "GET", f"{base}/xvwa/vulnerabilities/reflected_xss/?item={q}", None, None
        if site == "bWAPP": return "GET", f"{base}/xss_get.php?firstname={q}&lastname=PLGenN&form=submit", None, None
        return "GET", f"{base}/#/search?q={q}", None, None
    if category == "IDOR":
        if site == "XVWA": return "GET", f"{base}/xvwa/vulnerabilities/idor/?item={q}", None, None
        return "GET", f"{base}/rest/basket/{q}", None, None
    if category == "Command Injection":
        if site == "DVWA": return "POST", f"{base}/vulnerabilities/exec/", form({"ip": payload, "Submit": "Submit"}), "application/x-www-form-urlencoded"
        if site == "XVWA": return "GET", f"{base}/xvwa/vulnerabilities/cmdi/?target={q}", None, None
        return "POST", f"{base}/commandi.php", form({"target": payload, "form": "submit"}), "application/x-www-form-urlencoded"
    if category in ("Path Traversal", "Local File Inclusion"):
        if site == "DVWA": return "GET", f"{base}/vulnerabilities/fi/?page={q}", None, None
        return "GET", f"{base}/xvwa/vulnerabilities/fi/?file={q}", None, None
    if category == "XXE":
        return "POST", f"{base}/xxe-2.php", payload.encode("utf-8"), "application/xml"
    if category == "GraphQL Injection":
        return "POST", f"{base}/graphql", json.dumps({"query": payload}), "application/json"
    if category == "Open Redirect":
        if site == "XVWA": return "GET", f"{base}/xvwa/vulnerabilities/redirect/redirect.php?forward={q}", None, None
        return "GET", f"{base}/redirect?to={q}", None, None
    if category == "API Abuse":
        return "GET", f"{base}/rest/products/search?q={q}", None, None
    raise KeyError((site, category))


def loopback_url(url):
    p = urllib.parse.urlsplit(url)
    return p.scheme in ("http", "https") and (p.hostname or "").lower() in ALLOWED


def safe_to_submit(category, payload):
    if category == "Remote File Inclusion":
        return False, "Skipped: remote include can fetch/execute a remote file."
    if category == "SSRF":
        # XVWA's sink performs a fetch and writes a random file. Skip rather than create test artifacts.
        return False, "Skipped: available XVWA sink fetches the URL and writes a random image file."
    return True, ""


def result_count(site, category, body):
    if category != "SQL Injection": return 0
    text = html.unescape(body)
    if site == "DVWA": return len(re.findall(r"\bID:\s*", text, re.I))
    if site == "XVWA": return len(re.findall(r"Item\s+Code\s*:", text, re.I))
    # bWAPP's movie result table has a title cell per result row.
    return len(re.findall(r"<td>[^<]{1,200}</td>\s*<td\s+align=\"center\">", body, re.I))


async def response_body(resp, max_bytes=600000):
    if resp is None: return ""
    try:
        return (await resp.body())[:max_bytes].decode("utf-8", "ignore")
    except Exception:
        return ""


async def api_request(ctx, method, url, data=None, content_type=None):
    headers = {"content-type": content_type} if content_type else None
    opts = {"timeout": TIMEOUT, "max_redirects": 0}
    if method == "GET":
        return await ctx.get(url, **opts)
    return await ctx.post(url, data=data, headers=headers, **opts)


async def setup_context(browser, site, logins):
    context = await browser.new_context(ignore_https_errors=True, service_workers="block")
    blocked = {"count": 0}
    async def guard(route):
        host = (urllib.parse.urlsplit(route.request.url).hostname or "").lower()
        if host in ALLOWED:
            await route.continue_()
        else:
            blocked["count"] += 1
            await route.abort("blockedbyclient")
    await context.route("**/*", guard)
    page = await context.new_page()
    login = "not_required"
    try:
        if site == "DVWA":
            await page.goto(BASES[site] + "/login.php", wait_until="domcontentloaded", timeout=TIMEOUT)
            await page.locator('input[name="username"]').fill("admin")
            await page.locator('input[name="password"]').fill("password")
            await page.locator('input[name="Login"]').click()
            await page.goto(BASES[site] + "/security.php", wait_until="domcontentloaded", timeout=TIMEOUT)
            await page.locator('select[name="security"]').select_option("low")
            await page.locator('input[name="seclev_submit"]').click()
            login = "attempted_admin_password_security_low"
        elif site == "XVWA":
            await page.goto(BASES[site] + "/xvwa/", wait_until="domcontentloaded", timeout=TIMEOUT)
            if await page.locator("#username").count():
                await page.locator("#username").fill("admin")
                await page.locator("#password").fill("admin")
                if await page.locator("#btnLogin").count(): await page.locator("#btnLogin").click()
                login = "attempted_admin_admin"
            else:
                login = "no_login_form_seen"
        elif site == "bWAPP":
            await page.goto(BASES[site] + "/login.php", wait_until="domcontentloaded", timeout=TIMEOUT)
            await page.locator('input[name="login"]').fill("bee")
            await page.locator('input[name="password"]').fill("bug")
            await page.locator('button[name="form"]').click()
            # Set the training application to its intentionally vulnerable low level.
            if "security_level_set.php" in page.url or await page.get_by_text("Set your security level", exact=False).count():
                try:
                    await page.locator('select[name="security_level"]').select_option("0")
                    await page.locator('button[name="form_security_level"]').click()
                except Exception:
                    pass
            login = "attempted_bee_bug"
        else:
            login = "anonymous_local_test"
    except Exception as exc:
        login = "setup_issue:" + type(exc).__name__
    try:
        await page.screenshot(path=str(SHOTROOT / site / "session_ready.png"), full_page=True, timeout=10000)
    except Exception:
        pass
    logins[site] = login
    return context, page, blocked


def build_record(site, row, status=0, outcome="", confirmed=False, evidence="", location_host="", elapsed=0, error=""):
    return {
        "RunId": RUN_ID, "Site": site, "Category": row["category"], "Mode": row["mode"],
        "Index": row["index"], "Payload": row["payload"], "Status": status, "Outcome": outcome,
        "Confirmed": str(bool(confirmed)).lower(), "EvidenceCode": evidence,
        "LocationHost": location_host, "ElapsedMs": elapsed, "Error": error,
        "TestedUtc": dt.datetime.now(dt.timezone.utc).isoformat(),
    }


async def test_api_target(context, site, category, row, baseline_count=0, shot_page=None, screenshot_done=None):
    ok, why = safe_to_submit(category, row["payload"])
    if not ok:
        return build_record(site, row, outcome="SKIPPED_SAFETY_OR_SIDE_EFFECT", error=why)
    method, url, data, content_type = route_for(site, category, row["payload"])
    start = asyncio.get_running_loop().time()
    try:
        response = await api_request(context.request, method, url, data, content_type)
        status = response.status
        headers = response.headers
        body = await response_body(response)
        loc = headers.get("location", "")
        loc_host = (urllib.parse.urlsplit(loc).hostname or "") if loc else ""
        outcome, confirmed, evidence = "NO_CONFIRMATION_SIGNAL", False, ""
        if status >= 500:
            outcome, evidence = "SERVER_ERROR", "http_5xx"
        elif category == "SQL Injection":
            if re.search(r"SQL syntax|SQLSTATE|mysql_fetch|You have an error in your SQL|SQLite3::query", body, re.I):
                outcome, evidence = "SQL_ERROR_SIGNAL_UNCONFIRMED", "sql_error_text"
            else:
                n = result_count(site, category, body)
                if n > baseline_count and n > 0:
                    outcome, confirmed, evidence = "SQL_RESULT_DIFFERENTIAL", True, f"result_rows:{n};baseline:{baseline_count}"
        elif category == "Command Injection":
            if re.search(r"uid=\d+\([^)]*\)|root:x:0:0|Linux .* GNU/Linux", body, re.I):
                outcome, confirmed, evidence = "COMMAND_OUTPUT_CONFIRMED", True, "command_output_marker"
        elif category in ("Path Traversal", "Local File Inclusion"):
            if re.search(r"root:x:0:0:|\[boot loader\]|\[extensions\]", body, re.I):
                outcome, confirmed, evidence = "FILE_CONTENT_CONFIRMED", True, "known_local_file_marker"
        elif category == "XXE":
            if "root:x:0:0:" in body:
                outcome, confirmed, evidence = "XXE_FILE_READ_CONFIRMED", True, "passwd_marker"
            elif re.search(r"XML|DOCTYPE|ENTITY|parser", body, re.I):
                outcome, evidence = "XML_PARSER_SIGNAL_UNCONFIRMED", "xml_parse_or_reflection_text"
        elif category == "Open Redirect":
            if 300 <= status < 400 and loc:
                if loc_host.lower() not in ALLOWED:
                    outcome, confirmed, evidence = "EXTERNAL_REDIRECT_CONFIRMED", True, "external_location_not_followed"
                else:
                    outcome, evidence = "LOCAL_REDIRECT_ONLY", "redirect_location_local"
        elif category == "IDOR":
            if status == 200 and len(body) > 100:
                outcome, evidence = "OBJECT_RESPONSE_UNCONFIRMED", "object_returned_without_ownership_oracle"
        elif category == "GraphQL Injection":
            if status == 200 and re.search(r'"data"\s*:', body):
                outcome, evidence = "GRAPHQL_DATA_UNCONFIRMED", "data_field_without_access_control_oracle"
        elif category == "API Abuse":
            if status == 200:
                outcome, evidence = "API_RESPONSE_UNCONFIRMED", "http_200_without_privilege_or_rate_limit_oracle"

        # One representative browser screenshot for each supported site/category.
        key = (site, category)
        if shot_page and screenshot_done is not None and key not in screenshot_done and row["mode"] == "Basic" and row["index"] == "1":
            try:
                if method == "GET":
                    await shot_page.goto(url, wait_until="domcontentloaded", timeout=TIMEOUT)
                    await shot_page.screenshot(path=str(SHOTROOT / site / (category.lower().replace(" ", "_") + "_basic_1.png")), full_page=True, timeout=10000)
                else:
                    await shot_page.goto(BASES[site] + "/", wait_until="domcontentloaded", timeout=TIMEOUT)
                    await shot_page.screenshot(path=str(SHOTROOT / site / (category.lower().replace(" ", "_") + "_basic_1.png")), full_page=True, timeout=10000)
                screenshot_done.add(key)
            except Exception:
                screenshot_done.add(key)
        return build_record(site, row, status, outcome, confirmed, evidence, loc_host,
                            round((asyncio.get_running_loop().time() - start) * 1000), "")
    except Exception as exc:
        return build_record(site, row, outcome="REQUEST_ERROR", elapsed=round((asyncio.get_running_loop().time() - start) * 1000), error=type(exc).__name__)


async def test_xss(context, page, site, rows, screenshot_done):
    records = []
    state = {"dialog": False}
    async def dialog_handler(dialog):
        state["dialog"] = True
        # Do not store dialog contents: some payloads request document.cookie.
        try: await dialog.accept()
        except Exception: pass
    page.on("dialog", dialog_handler)
    for row in rows:
        ok, why = safe_to_submit("XSS", row["payload"])
        assert ok
        _, url, _, _ = route_for(site, "XSS", row["payload"])
        state["dialog"] = False
        start = asyncio.get_running_loop().time()
        status, body, error = 0, "", ""
        try:
            resp = await page.goto(url, wait_until="domcontentloaded", timeout=TIMEOUT)
            status = resp.status if resp else 0
            body = await response_body(resp)
            # Allow SPA rendering and event handlers to run before deciding.
            await page.wait_for_timeout(80)
        except Exception as exc:
            error = type(exc).__name__
        confirmed = bool(state["dialog"])
        if confirmed:
            outcome, evidence = "JAVASCRIPT_DIALOG_CONFIRMED", "browser_dialog_event"
        elif status >= 500:
            outcome, evidence = "SERVER_ERROR", "http_5xx"
        else:
            decoded = html.unescape(body)
            # Reflection is recorded as a signal only; it is not a confirmed XSS.
            reflected = row["payload"] in body or row["payload"] in decoded or "alert" in decoded.lower()
            outcome = "REFLECTED_NOT_EXECUTED" if reflected else "NO_CONFIRMATION_SIGNAL"
            evidence = "payload_reflected_without_dialog" if reflected else "no_dialog_or_reflection"
        key = (site, "XSS")
        if key not in screenshot_done and row["mode"] == "Basic" and row["index"] == "1":
            try:
                await page.screenshot(path=str(SHOTROOT / site / "xss_basic_1.png"), full_page=True, timeout=10000)
                screenshot_done.add(key)
            except Exception:
                screenshot_done.add(key)
        records.append(build_record(site, row, status, outcome, confirmed, evidence, "",
                                    round((asyncio.get_running_loop().time() - start) * 1000), error))
    return records


async def main():
    if not INPUT.exists(): raise FileNotFoundError(INPUT)
    with INPUT.open(encoding="utf-8-sig", newline="") as f:
        app_rows = list(csv.DictReader(f))
    if not app_rows: raise RuntimeError("No generated payload rows found")
    for site in BASES: (SHOTROOT / site).mkdir(parents=True, exist_ok=True)
    logins, contexts, pages, blocked = {}, {}, {}, {}
    results = []
    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True, executable_path=r"C:\Program Files\Google\Chrome\Application\chrome.exe")
        for site in BASES:
            contexts[site], pages[site], blocked[site] = await setup_context(browser, site, logins)

        # Capture visible XSS behavior in an actual browser; other routes use local API requests.
        screenshot_done = set()
        for site in BASES:
            xss_rows = [r for r in app_rows if r["category"] == "XSS"]
            results.extend(await test_xss(contexts[site], pages[site], site, xss_rows, screenshot_done))
            print(f"XSS {site}: {len(xss_rows)} payload navigations complete", flush=True)

        # Save SQL baseline counts, then compare result-row counts against benign controls.
        baselines = {}
        for site in SPECS["SQL Injection"]:
            try:
                if site == "DVWA":
                    resp = await contexts[site].request.get(BASES[site] + "/vulnerabilities/sqli/?id=1&Submit=Submit", timeout=TIMEOUT, max_redirects=0)
                elif site == "XVWA":
                    resp = await contexts[site].request.post(BASES[site] + "/xvwa/vulnerabilities/sqli/", data=form({"search": "codex_nonexistent_control_2026"}), headers={"content-type":"application/x-www-form-urlencoded"}, timeout=TIMEOUT, max_redirects=0)
                else:
                    resp = await contexts[site].request.get(BASES[site] + "/sqli_1.php?title=codex_nonexistent_control_2026&action=search", timeout=TIMEOUT, max_redirects=0)
                baselines[site] = result_count(site, "SQL Injection", await response_body(resp))
            except Exception:
                baselines[site] = 0

        jobs = []
        for category, sites in SPECS.items():
            if category == "XSS": continue
            rows = [r for r in app_rows if r["category"] == category]
            if not sites:
                # Keep an explicit row per app payload when no safe supported sink exists.
                for site in ("XVWA",):
                    for r in rows:
                        reason = safe_to_submit(category, r["payload"])[1]
                        results.append(build_record(site, r, outcome="SKIPPED_SAFETY_OR_SIDE_EFFECT", error=reason))
                continue
            for site in sites:
                for r in rows:
                    jobs.append((site, category, r))

        sem = asyncio.Semaphore(8)
        async def execute(job):
            site, category, row = job
            async with sem:
                return await test_api_target(contexts[site], site, category, row,
                    baselines.get(site, 0), pages[site], screenshot_done)

        for start in range(0, len(jobs), 40):
            batch = await asyncio.gather(*(execute(j) for j in jobs[start:start+40]))
            results.extend(batch)
            print(f"API-like requests completed: {min(start+40,len(jobs))}/{len(jobs)}", flush=True)
        # Sort into deterministic output order for audits.
        category_order = list(SPECS)
        site_order = list(BASES)
        results.sort(key=lambda r: (category_order.index(r["Category"]), site_order.index(r["Site"]),
                                    ["Basic","Advanced","Evasion"].index(r["Mode"]), int(r["Index"])))
        with OUT.open("w", encoding="utf-8-sig", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=FIELDS)
            writer.writeheader(); writer.writerows(results)
        summary = Counter((r["Site"],r["Category"],r["Outcome"],r["Confirmed"]) for r in results)
        META.write_text(json.dumps({
            "run_id": RUN_ID,
            "tested_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(),
            "input_rows": len(app_rows),
            "result_rows": len(results),
            "browser": "Google Chrome via Playwright headless; page requests restricted to localhost/127.0.0.1/::1",
            "api_requests": "Only local base URLs; redirects were not followed; response bodies were not persisted.",
            "login_attempts": logins,
            "blocked_nonlocal_browser_requests": {k:v["count"] for k,v in blocked.items()},
            "sql_baseline_result_counts": baselines,
            "confirmation_counts": {"|".join(k):v for k,v in summary.items()},
            "unsupported_or_skipped": {
                "Remote File Inclusion": "Skipped: app payloads contain remote include URLs; no server-side remote fetch performed.",
                "SSRF": "Skipped: only XVWA sink is available; it fetches submitted URL and writes a random image file. Avoided creating files and blocked any off-loopback destination.",
                "other category/site pairs": "Not applicable because no matching handler/oracle was available; not scored as negative.",
            },
            "result_csv": str(OUT),
        }, indent=2), encoding="utf-8")
        for site, context in contexts.items(): await context.close()
        await browser.close()
    print(json.dumps({"run_id":RUN_ID,"rows":len(results),"confirmed":sum(r["Confirmed"]=="true" for r in results),"output":str(OUT)}, indent=2), flush=True)


if __name__ == "__main__":
    asyncio.run(main())

